import Link from "next/link";
import { PageShell } from "@/components/layout/PageShell";
import { StateBadge } from "@/components/ui/StateBadge";
import { EmptyState, ErrorState, Panel } from "@/components/ui/Panel";
import { GenerateReportButton } from "@/components/reports/GenerateReportButton";
import { errorMessage, getMe, list } from "@/lib/server/api";
import { canEdit, dateTime } from "@/lib/format";
import type { AuditReportRow, AuditRun } from "@/lib/types";

export const dynamic = "force-dynamic";

export default async function ReportsPage() {
  let reports: AuditReportRow[] = [];
  let ready: AuditRun[] = [];
  let role = "";
  let failure: string | null = null;
  try {
    const [rep, runs, me] = await Promise.all([list<AuditReportRow>("/ai/reports/"), list<AuditRun>("/ai/runs/"), getMe()]);
    reports = rep;
    role = me.active_membership?.role ?? "";
    const reported = new Set(rep.map((r) => r.run));
    ready = runs.filter((r) => r.status === "completed" && !reported.has(r.id));
  } catch (error) {
    failure = errorMessage(error);
  }

  return (
    <PageShell title="Reports" subtitle="Frozen, versioned audit reports with a reviewer sign-off">
      <p className="text-xs text-slate-400 max-w-3xl" id="reports-help">
        What this shows: each report is a frozen copy of a completed audit, with a fingerprint so later changes are detectable. A report moves from
        draft to in review to approved, and the person who approves it must be different from the person who generated or submitted it.
      </p>
      {failure && <ErrorState message={failure} />}
      {!failure && reports.length === 0 && ready.length === 0 && (
        <EmptyState title="No reports yet">Run an audit from the Audits page. Once it completes you can generate a report here.</EmptyState>
      )}
      {reports.length > 0 && (
        <div className="glass-panel overflow-x-auto">
          <table className="w-full text-sm" aria-describedby="reports-help">
            <caption className="sr-only">Audit reports</caption>
            <thead>
              <tr className="text-left text-xs text-slate-400 border-b border-white/10">
                <th scope="col" className="p-3 font-medium">Report</th>
                <th scope="col" className="p-3 font-medium">Status</th>
                <th scope="col" className="p-3 font-medium">Audit date</th>
                <th scope="col" className="p-3 font-medium">Generated by</th>
                <th scope="col" className="p-3 font-medium">Approved by</th>
              </tr>
            </thead>
            <tbody>
              {reports.map((r) => (
                <tr key={r.id} className="border-b border-white/5 align-top">
                  <td className="p-3">
                    <Link href={`/reports/${r.id}`} className="font-semibold text-cyan-300 hover:text-cyan-200 focus:outline-none focus:ring-2 focus:ring-cyan-400 rounded">
                      {r.system_name} v{r.version}
                    </Link>
                    <div className="text-xs text-slate-500">model {r.model_version_label}</div>
                  </td>
                  <td className="p-3"><StateBadge state={r.status} /></td>
                  <td className="p-3 text-xs text-slate-300">{dateTime(r.audit_date)}</td>
                  <td className="p-3 text-xs text-slate-300">{r.generated_by_name ?? "Unknown"}<div className="text-slate-500">{dateTime(r.created_at)}</div></td>
                  <td className="p-3 text-xs text-slate-300">
                    {r.approved_by_name ? <>{r.approved_by_name}<div className="text-slate-500">{dateTime(r.approved_at)}</div></> : <span className="text-slate-500">Not approved</span>}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
      {ready.length > 0 && (
        <Panel title="Completed audits without a report">
          <ul className="space-y-3">
            {ready.map((r) => (
              <li key={r.id} className="flex flex-wrap items-center gap-3">
                <span className="font-semibold text-cyan-300">{r.system_name}</span>
                <span className="text-xs text-slate-400">model {r.model_version_label}, finished {dateTime(r.finished_at)}</span>
                <span className="ml-auto">{canEdit(role) ? <GenerateReportButton runId={r.id} /> : <span className="text-xs text-slate-500">Read-only role</span>}</span>
              </li>
            ))}
          </ul>
        </Panel>
      )}
    </PageShell>
  );
}